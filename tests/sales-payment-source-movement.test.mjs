import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { classifyV3Recovery, REQUIRED_V3_MODULES } from '../common/v3-status-contract.mjs';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = readFileSync(join(root,'common/recovery-controller.mjs'),'utf8');
const paymentBranch = source.split("if(mod==='sales-payment') {")[1]?.split("if(mod==='purchase-return') {")[0];
assert.ok(paymentBranch, 'SP branch present');
assert.match(source,/function exec\(mod, file, argv=\[\],allowed=\[0\], withExit=false\)/);
assert.match(source,/return withExit \? \{ text: output, exit: r.status \} : output/);
assert.match(paymentBranch,/presence\.mjs',\[\],\[0,3\],true/);
assert.match(paymentBranch,/check\.mjs',\[\],\[0,3\],true/);
assert.match(paymentBranch,/p\.exit===3/);
assert.match(paymentBranch,/c\.exit===3/);
assert.match(paymentBranch,/SALES PAYMENT PRESENCE NEEDS_REVIEW/);
assert.match(paymentBranch,/SALES PAYMENT CHECK NEEDS_REVIEW/);
assert.match(paymentBranch,/summary\.push\(\[mod,'NEEDS_REVIEW'\]\)/);
assert.match(paymentBranch,/SALES PAYMENT FINANCIAL CHECK PASS/);
assert.match(paymentBranch,/specialDeletionGuard\(mod\)/);
assert.match(source,/if\(mod==='purchase-return'\)/);
assert.match(source,/if\(mod==='sales-return'\)/);
const all = Object.fromEntries(REQUIRED_V3_MODULES.map(x=>[x,'FINAL_PASS']));
function report(states) {return '========== RECOVERY SUMMARY ==========\n'+Object.entries(states).map(([k,v])=>`${k}: ${v}`).join('\n');}
assert.equal(classifyV3Recovery(0, report(all)), 'FINAL_PASS');
assert.equal(classifyV3Recovery(3, report({...all,'sales-payment':'NEEDS_REVIEW'})), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(1, report({...all,'sales-payment':'ERROR'})), 'FAILED');
assert.equal(classifyV3Recovery(0, report({...all,'purchase-return':'NO_SOURCE'})), 'FINAL_PASS');
console.log('SALES PAYMENT B6.1 SOURCE MOVEMENT CONTRACT PASS');
