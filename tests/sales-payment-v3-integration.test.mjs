import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { REQUIRED_V3_MODULES, classifyV3Recovery } from '../common/v3-status-contract.mjs';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const summary=(o)=>'========== RECOVERY SUMMARY ==========\n'+Object.entries(o).map(([k,v])=>`${k}: ${v}`).join('\n');
const all=Object.fromEntries(REQUIRED_V3_MODULES.map(m=>[m,'FINAL_PASS']));
assert.equal(REQUIRED_V3_MODULES.length,9);
assert.equal(classifyV3Recovery(0,summary(all)), 'FINAL_PASS');
assert.equal(classifyV3Recovery(0,summary({...all,'purchase-return':'NO_SOURCE'})), 'FINAL_PASS');
assert.equal(classifyV3Recovery(0,summary({...all,'sales-payment':'NO_SOURCE'})), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(0,summary({...all,'sales-payment':'NEEDS_REVIEW'})), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(0,summary({...all,'sales-payment':'ERROR'})), 'FAILED');
assert.equal(classifyV3Recovery(0,summary({...all,'purchase-return':'ERROR'})), 'FAILED');
assert.equal(classifyV3Recovery(0,summary({...all,'sales-payment':undefined}).replace('sales-payment: undefined','')), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(0,summary(all)+'\nsales-payment: FINAL_PASS'), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(1,summary(all)), 'FAILED');
assert.equal(classifyV3Recovery(3,summary(all)), 'NEEDS_REVIEW');
assert.equal(classifyV3Recovery(0,summary(all),true), 'FAILED');
const recovery=readFileSync(join(root,'common/recovery-controller.mjs'),'utf8');
const fast=readFileSync(join(root,'scripts/fast-delta.mjs'),'utf8');
assert.match(recovery,/if\(mod==='sales-payment'\)/);
assert.match(recovery,/if\(!specialDeletionGuard\(mod\)\)/);
assert.match(recovery,/SP financial check marker absent/);
assert.match(recovery,/if\(mod==='purchase-return'\)/);
assert.match(fast,/sales-payment.*SALES PAYMENT SYNC SUCCESS/);
assert.match(fast,/sales-return','sales-payment'\].includes\(mod\)/);
assert.match(fast,/PURCHASE RETURN GATE: NO_SOURCE/);
console.log('SALES PAYMENT V3 INTEGRATION CONTRACT PASS: 18 checks');
